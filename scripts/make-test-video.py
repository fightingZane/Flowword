"""生成项目自建的有限时长 WebM 测试视频，不下载任何外部媒体"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import cv2
import numpy as np


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--seconds", type=int, default=90, help="视频长度，默认 90 秒")
    args = parser.parse_args()
    if not 60 <= args.seconds <= 600:
        parser.error("测试视频长度应在 60 到 600 秒之间")

    # 路径以脚本所在项目为准，生成文件始终留在当前项目内
    project = Path(__file__).resolve().parent.parent
    output = project / "tests" / "fixtures" / "test-video.webm"
    output.parent.mkdir(parents=True, exist_ok=True)
    width, height, fps = 640, 360, 5
    writer = cv2.VideoWriter(
        str(output), cv2.CAP_FFMPEG, cv2.VideoWriter_fourcc(*"VP80"), fps, (width, height)
    )   # 使用现有 OpenCV 的 FFmpeg 后台编码 VP8，不添加生产依赖
    if not writer.isOpened():
        raise RuntimeError("当前 OpenCV 无法编码 VP8，请在支持 FFmpeg 后台的测试环境运行")

    # 背景、文字、圆环和进度条都由脚本绘制，没有第三方素材
    blend = np.linspace(0, 1, width, dtype=np.float32)[None, :, None]
    left = np.array([53, 51, 18], dtype=np.float32)[None, None, :]
    right = np.array([72, 92, 52], dtype=np.float32)[None, None, :]
    background = np.repeat((left + (right - left) * blend).astype(np.uint8), height, axis=0)
    font = cv2.FONT_HERSHEY_SIMPLEX
    for radius in range(40, 240, 24):
        cv2.circle(background, (578, 84), radius, (82, 105, 78), 1, cv2.LINE_AA)
    cv2.putText(background, "FLOWWORD / LOCAL TEST", (36, 96), font, 0.38, (164, 194, 177), 1, cv2.LINE_AA)
    cv2.putText(background, "A small pause.", (36, 148), font, 1.0, (222, 242, 238), 2, cv2.LINE_AA)
    cv2.putText(background, "A little more clarity.", (36, 197), font, 0.9, (222, 242, 238), 2, cv2.LINE_AA)
    cv2.putText(background, "Synthetic video - no external media", (37, 239), font, 0.42, (151, 176, 156), 1, cv2.LINE_AA)
    frame_count = args.seconds * fps
    try:
        for index in range(frame_count):
            frame = background.copy()
            elapsed = index / fps
            label = f"{elapsed:05.1f}s / {args.seconds}s"
            cv2.putText(frame, label, (37, 314), font, 0.45, (193, 216, 197), 1, cv2.LINE_AA)
            progress = round((width - 74) * index / max(1, frame_count - 1))
            cv2.rectangle(frame, (37, 335), (width - 37, 338), (93, 117, 92), -1)
            cv2.rectangle(frame, (37, 335), (37 + progress, 338), (160, 201, 183), -1)
            writer.write(frame)   # 每帧都有真实编码时间戳，浏览器无需覆盖 duration
    finally:
        writer.release()   # 写入 WebM 索引和有限时长元数据后再验证文件

    # OpenCV 解码检查用于快速发现编码失败，浏览器端另外验证原生 duration
    probe = cv2.VideoCapture(str(output), cv2.CAP_FFMPEG)
    try:
        decoded_frames = int(probe.get(cv2.CAP_PROP_FRAME_COUNT))
        decoded_fps = float(probe.get(cv2.CAP_PROP_FPS))
        readable, _ = probe.read()
        if not readable or decoded_frames != frame_count or abs(decoded_fps - fps) > 0.01:
            raise RuntimeError("生成媒体的帧数或帧率校验失败")
    finally:
        probe.release()
    print(json.dumps({
        "file": str(output), "codec": "VP8/WebM", "frames": frame_count,
        "fps": decoded_fps, "durationSeconds": decoded_frames / decoded_fps,
        "bytes": output.stat().st_size, "sha256": hashlib.sha256(output.read_bytes()).hexdigest(),
        "source": "All frames generated by this script; no third-party media", "audio": False,
    }, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
